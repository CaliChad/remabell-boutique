export const shopProducts = products.filter(p => !p.isVirtual);

// Turns a name into the text used in a web address:
// "Rich Glow Face Cream" -> "rich-glow-face-cream"
export function slugify(text) {
    return String(text)
        .toLowerCase()
        .replace(/&/g, ' and ')
        .replace(/['\u2018\u2019]/g, '')
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, '');
}

// A product's own link text. It is stored on the product, so renaming a product
// never breaks a link that is already running in an ad.
export function productSlug(product) {
    return product.slug || slugify(product.name);
}

export function getProductBySlug(slug) {
    return shopProducts.find(p => productSlug(p) === slug);
}

// Category names in web addresses: "Body Lotions & Milks" -> "body-lotions-and-milks"
export function getCategoryBySlug(slug) {
    return categories.find(c => slugify(c) === slug);
}
